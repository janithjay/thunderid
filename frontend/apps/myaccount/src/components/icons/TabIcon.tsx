/**
 * The icon of a tab: the image or the named icon it was given, else its built-in icon, or the information icon
 * for a custom one. An image that fails to load falls back to the icon the tab would have without it.
 */
export default function TabIcon({tab}: {tab: AccountTab}): ReactElement {
  const [failed, setFailed] = useState<string | null>(null);

  if (tab.iconUrl && failed !== tab.iconUrl) {
    return (
      <img
        src={tab.iconUrl}
        alt=""
        width={20}
        height={20}
        className="tab-icon-image"
        onError={() => setFailed(tab.iconUrl ?? null)}
      />
    );
  }
  if (tab.icon) {
    return <Svg>{PATHS[tab.icon] ?? PATHS.info}</Svg>;
  }
  if (!tab.custom && tab.id === 'personal') {
    // SDK icon, sized to match the other 20px icons.
    return <UserIcon width={20} height={20} strokeWidth={1.75} aria-hidden="true" />;
  }
  return <Svg>{PATHS[tab.custom ? 'info' : tab.id] ?? PATHS.info}</Svg>;
}
